-- Ejecutar conectado a una base administrativa, por ejemplo: psql -U postgres -f database.sql
-- gexec es una instrucción de psql: crea la base solo si aún no existe.
SELECT 'CREATE DATABASE huertos'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'huertos')
\gexec

\connect huertos

CREATE TABLE IF NOT EXISTS parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    location_latitude DOUBLE PRECISION NOT NULL CHECK (location_latitude BETWEEN -90 AND 90),
    location_longitude DOUBLE PRECISION NOT NULL CHECK (location_longitude BETWEEN -180 AND 180),
    soil_type VARCHAR(20) NOT NULL CHECK (soil_type IN ('ARCILLOSO', 'LIMOSO', 'ARENOSO')),
    owner_or_lead VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
